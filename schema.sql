CREATE TABLE users (
 id INT AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role ENUM('admin','employee') NOT NULL DEFAULT 'employee',
 active TINYINT(1) NOT NULL DEFAULT 1,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE settings (
 id TINYINT PRIMARY KEY DEFAULT 1,
 company_name VARCHAR(190) NOT NULL DEFAULT 'FG Servicios e Instalaciones',
 tax_id VARCHAR(80) DEFAULT '',
 phone VARCHAR(80) DEFAULT '',
 email VARCHAR(190) DEFAULT '',
 address VARCHAR(255) DEFAULT '',
 logo_path VARCHAR(255) DEFAULT '',
 quote_prefix VARCHAR(20) NOT NULL DEFAULT 'FG',
 next_quote_number INT NOT NULL DEFAULT 1,
 default_validity INT NOT NULL DEFAULT 15,
 notes TEXT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
