CREATE TABLE clients (
 id INT AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(190) NOT NULL,
 tax_id VARCHAR(80) DEFAULT '',
 phone VARCHAR(80) DEFAULT '',
 email VARCHAR(190) DEFAULT '',
 address VARCHAR(255) DEFAULT '',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE catalog (
 id INT AUTO_INCREMENT PRIMARY KEY,
 description VARCHAR(255) NOT NULL,
 unit VARCHAR(40) NOT NULL DEFAULT 'unidad',
 price_ars DECIMAL(14,2) NOT NULL DEFAULT 0,
 price_usd DECIMAL(14,2) NOT NULL DEFAULT 0,
 active TINYINT(1) NOT NULL DEFAULT 1,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE quotes (
 id INT AUTO_INCREMENT PRIMARY KEY,
 number VARCHAR(60) NOT NULL UNIQUE,
 client_id INT NOT NULL,
 created_by INT NOT NULL,
 currency CHAR(3) NOT NULL DEFAULT 'ARS',
 exchange_rate DECIMAL(14,4) DEFAULT NULL,
 issue_date DATE NOT NULL,
 valid_until DATE DEFAULT NULL,
 status ENUM('borrador','enviado','aprobado','rechazado') NOT NULL DEFAULT 'borrador',
 notes TEXT,
 subtotal DECIMAL(14,2) NOT NULL DEFAULT 0,
 discount DECIMAL(14,2) NOT NULL DEFAULT 0,
 total DECIMAL(14,2) NOT NULL DEFAULT 0,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_quote_client FOREIGN KEY (client_id) REFERENCES clients(id),
 CONSTRAINT fk_quote_user FOREIGN KEY (created_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE quote_items (
 id INT AUTO_INCREMENT PRIMARY KEY,
 quote_id INT NOT NULL,
 description VARCHAR(255) NOT NULL,
 quantity DECIMAL(12,2) NOT NULL DEFAULT 1,
 unit VARCHAR(40) NOT NULL DEFAULT 'unidad',
 unit_price DECIMAL(14,2) NOT NULL DEFAULT 0,
 line_total DECIMAL(14,2) NOT NULL DEFAULT 0,
 CONSTRAINT fk_item_quote FOREIGN KEY (quote_id) REFERENCES quotes(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
